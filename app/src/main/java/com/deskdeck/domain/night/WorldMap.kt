/**
 * A dotted world map for the World clock face: coarse continent outlines (lon, lat), rasterized
 * once into a grid of land dots, plus where the sun is and where the day/night line runs.
 * Equirectangular, from [TOP_LAT] to [BOTTOM_LAT] (no Antarctica), −180..180 longitude.
 */
object WorldMap {
    const val TOP_LAT = 80.0
    const val BOTTOM_LAT = -56.0

    /** A land dot at the center of a grid cell. */
    data class Dot(val lon: Double, val lat: Double)

    /** Land dots on a [cols] × rows grid (rows follow from the cell size). */
    fun landDots(cols: Int): List<Dot> {
        val step = 360.0 / cols
        val rows = ((TOP_LAT - BOTTOM_LAT) / step).toInt()
        val dots = ArrayList<Dot>()
        for (r in 0 until rows) {
            val lat = TOP_LAT - (r + 0.5) * step
            for (c in 0 until cols) {
                val lon = -180 + (c + 0.5) * step
                if (isLand(lon, lat)) dots += Dot(lon, lat)
            }
        }
        return dots
    }

    fun isLand(lon: Double, lat: Double): Boolean = LAND.any { contains(it, lon, lat) }

    /** Where the sun is overhead (degrees), ignoring the equation of time (a few minutes). */
    fun subsolarPoint(at: Instant): Dot {
        val utc = at.atOffset(ZoneOffset.UTC)
        val day = utc.dayOfYear
        val hours = utc.hour + utc.minute / 60.0 + utc.second / 3600.0
        val declination = -23.44 * cos(2 * PI / 365 * (day + 10))
        var lon = -(hours - 12) * 15
        if (lon < -180) lon += 360
        if (lon > 180) lon -= 360
        return Dot(lon, declination)
    }

    /** Whether the sun is up at [lon], [lat]. */
    fun isDay(lon: Double, lat: Double, sun: Dot): Boolean {
        val r = PI / 180
        val altitude = sin(lat * r) * sin(sun.lat * r) + cos(lat * r) * cos(sun.lat * r) * cos((lon - sun.lon) * r)
        return altitude > 0
    }

    /** The latitude of the day/night line at [lon] (the terminator), clamped to the map. */
    fun terminatorLat(lon: Double, sun: Dot): Double {
        val r = PI / 180
        // Near the equinoxes the sun's declination is ~0 and the line is almost vertical.
        val dec = if (kotlin.math.abs(sun.lat) < 0.1) 0.1 * (if (sun.lat < 0) -1 else 1) else sun.lat
        val lat = atan(-cos((lon - sun.lon) * r) / tan(dec * r)) / r
        return lat.coerceIn(BOTTOM_LAT, TOP_LAT)
    }

    /** Ray casting point-in-polygon on (lon, lat) pairs. */
    private fun contains(poly: DoubleArray, x: Double, y: Double): Boolean {
        var inside = false
        val n = poly.size / 2
        var j = n - 1
        for (i in 0 until n) {
            val xi = poly[2 * i]
            val yi = poly[2 * i + 1]
            val xj = poly[2 * j]
            val yj = poly[2 * j + 1]
            if ((yi > y) != (yj > y) && x < (xj - xi) * (y - yi) / (yj - yi) + xi) inside = !inside
            j = i
        }
        return inside
    }

